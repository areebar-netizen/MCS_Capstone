def detect_flat_and_spikes(df, channels, window_size=256, flat_var_thresh=1e-6, spike_std_thresh=5):
    """
    Detect flat lines and spikes in EEG data from Muse headband.

    Parameters:
    - df: pandas DataFrame with 'timestamp' + EEG channels
    - channels: list of EEG channels ['TP9','AF7','AF8','TP10']
    - window_size: number of samples to compute variance for flat detection
    - flat_var_thresh: variance threshold to consider a flat line
    - spike_std_thresh: number of standard deviations to consider a spike

    Returns:
    - flat_dict: dictionary with channel -> list of flat line indices
    - spike_dict: dictionary with channel -> list of spike indices
    """
    flat_dict = {}
    spike_dict = {}

    for ch in channels:
        signal = df[ch].values

        # --- Flat line detection ---
        flat_indices = []
        for i in range(len(signal) - window_size):
            window = signal[i:i+window_size]
            if np.var(window) < flat_var_thresh:
                flat_indices.append(i)
        flat_dict[ch] = flat_indices

        # --- Spike detection ---
        mean = np.mean(signal)
        std = np.std(signal)
        spike_indices = np.where(np.abs(signal - mean) > spike_std_thresh * std)[0]
        spike_dict[ch] = spike_indices

    return flat_dict, spike_dict


