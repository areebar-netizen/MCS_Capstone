def plot_eeg_with_all_artifacts(df, channels, flat_dict, spike_dict, hf_dict, hv_dict):
    n_channels = len(channels)
    fig, axes = plt.subplots(n_channels, 1, figsize=(16, 3*n_channels), sharex=True)

    if n_channels == 1:
        axes = [axes]

    for i, ch in enumerate(channels):
        ax = axes[i]
        signal = df[ch].values
        t = df['lsl_timestamp'].values

        ax.plot(t, signal, color='blue', label='EEG signal')

        # Flat lines (red)
        flat_idx = flat_dict[ch]
        if len(flat_idx) > 0:
            ax.scatter(t[flat_idx], signal[flat_idx], color='red', s=10, label='Flat line')

        # Spikes (green)
        spike_idx = spike_dict[ch]
        if len(spike_idx) > 0:
            ax.scatter(t[spike_idx], signal[spike_idx], color='green', s=10, label='Spikes')

        # High-frequency (orange)
        hf_idx = hf_dict[ch]
        if len(hf_idx) > 0:
            ax.scatter(t[hf_idx], signal[hf_idx], color='orange', s=5, label='High-Freq')

        # High-variance (purple)
        hv_idx = hv_dict[ch]
        if len(hv_idx) > 0:
            ax.scatter(t[hv_idx], signal[hv_idx], color='yellow', s=5, label='High-Variance')

        ax.set_ylabel(f'{ch} (μV)')
        ax.legend(loc='upper right')
        ax.grid(True)

    axes[-1].set_xlabel('Time (s)')
    plt.suptitle('EEG Channels with Flat Lines (red), Spikes (green), High-Frequency (orange), High-Variance (purple)', fontsize=16)
    plt.tight_layout(rect=[0,0,1,0.95])
    plt.show()

