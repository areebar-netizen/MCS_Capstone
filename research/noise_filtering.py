# -------------------------
# Block 5: Combine all steps to get features
# -------------------------
def feature_fft(matrix, period=1., mains_f=50.,
                filter_mains=True, filter_DC=True,
                normalise_signals=True,
                ntop=10, get_power_spectrum=True):
    if normalise_signals:
        matrix = normalize_signals(matrix)
    fft_vals, freqs = compute_fft(matrix, period)
    fft_vals, freqs = filter_fft(fft_vals, freqs, filter_DC, filter_mains, mains_f)

    # Extract top-N frequencies
    top_freqs = top_n_frequencies(fft_vals, freqs, ntop)
    ret = top_freqs

    # Make feature names
    names = []
    for i in range(fft_vals.shape[1]):
        names.extend(['topFreq_' + str(j) + "_" + str(i) for j in range(1, ntop+1)])

    # Append full power spectrum if requested
    if get_power_spectrum:
        ret = np.hstack([ret, fft_vals.flatten(order='F')])
        for i in range(fft_vals.shape[1]):
            names.extend(['freq_' + "{:03d}".format(int(j)) + "_" + str(i) for j in 10*np.round(freqs, 1)])

    return ret, names

