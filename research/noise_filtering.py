from scipy.fft import fft

def compute_fft(matrix, period=1.0):
    """
    Compute absolute FFT of each column in matrix.
    Returns FFT values and corresponding frequencies.
    """
    N = matrix.shape[0]
    T = period / N  # sampling period
    fft_values = np.abs(fft(matrix, axis=0))[0:N//2] * 2 / N
    freqs = np.linspace(0.0, 1.0/(2.0*T), N//2)
    return fft_values, freqs

# Example usage
