# -----------------------------
# 1. Bandpass filter
# -----------------------------
def bandpass_filter(signal, lowcut=1, highcut=45, fs=256, order=4):
    nyq = 0.5 * fs
    b, a = butter(order, [lowcut/nyq, highcut/nyq], btype='band')
    return filtfilt(b, a, signal)

# -----------------------------
# 2. Notch filter
# -----------------------------
def notch_filter(signal, freq=50, fs=256, Q=30):
    b, a = iirnotch(freq/(fs/2), Q)
    return filtfilt(b, a, signal)

# -----------------------------
# 3. Apply filters to multiple channels
# -----------------------------
def apply_filters(df, channels, fs=256, lowcut=1, highcut=45, notch_freq=50):
    df_filtered = df.copy()
    for ch in channels:
        sig = df[ch].values
        sig_bp = bandpass_filter(sig, lowcut=lowcut, highcut=highcut, fs=fs)
        sig_filt = notch_filter(sig_bp, freq=notch_freq, fs=fs)
        df_filtered[ch] = sig_filt
    return df_filtered

