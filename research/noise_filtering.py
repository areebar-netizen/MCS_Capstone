# -------------------------
# Block 3: Filter DC and mains frequency
# -------------------------
def filter_fft(fft_values, freqs, filter_DC=True, filter_mains=True, mains_f=50):
    """
    Removes DC (0 Hz) and mains frequency (±1 Hz) from FFT values and frequencies.
    """
    if filter_DC:
        fft_values = fft_values[1:]
        freqs = freqs[1:]
    if filter_mains:
        indx = np.where(np.abs(freqs - mains_f) <= 1)
        fft_values = np.delete(fft_values, indx, axis=0)
        freqs = np.delete(freqs, indx)
    return fft_values, freqs

# Example usage
fft_filtered, freqs_filtered = filter_fft(fft_vals, freqs)

# -------------------------
# Block 4: Extract top-N frequency components
# -------------------------
def top_n_frequencies(fft_values, freqs, ntop=10):
    """
    Returns the top-N frequencies (highest FFT magnitude) for each signal.
    """
    # Sort indices for each column
    indx = np.argsort(fft_values, axis=0)[::-1][:ntop]
    top_freqs = freqs[indx].flatten(order='F')
    return top_freqs

