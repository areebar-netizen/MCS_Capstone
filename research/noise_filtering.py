def detect_high_frequency_channels(eeg_data, fs=256, hf_freq=30, hf_ratio=0.3, window_sec=1.0, channels=None):
    """
    Detects segments where high-frequency power dominates for each EEG channel.

    Parameters:
        eeg_data (np.array): [nsamples x n_channels] EEG signals
        fs (int): sampling rate in Hz
        hf_freq (float): frequency threshold to consider high-frequency (Hz)
        hf_ratio (float): fraction of power above hf_freq to mark as high-frequency
        window_sec (float): window size for FFT analysis (seconds)
        channels (list): list of channel names (optional)

    Returns:
        hf_dict (dict): {channel_name: array of indices of high-frequency segments}
    """
    if channels is None:
        channels = [f'ch{i}' for i in range(eeg_data.shape[1])]

    n_channels = eeg_data.shape[1]
    hf_dict = {}

    for i in range(n_channels):
        sig = eeg_data[:, i]
        window_size = int(fs * window_sec)
        hf_indices = []

        for start in range(0, len(sig) - window_size, window_size):
            window = sig[start:start+window_size]
            fft_vals = np.abs(np.fft.rfft(window))
            freqs = np.fft.rfftfreq(len(window), d=1/fs)

            total_power = np.sum(fft_vals)
            hf_power = np.sum(fft_vals[freqs > hf_freq])
            if total_power > 0 and (hf_power / total_power) > hf_ratio:
                hf_indices.extend(range(start, start + window_size))

        hf_dict[channels[i]] = np.array(hf_indices)

    return hf_dict

