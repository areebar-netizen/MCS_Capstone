def plot_filtered_vs_raw_with_artifacts(df_raw, df_filtered, channels, flat_dict, spike_dict, hf_dict, hv_dict, start=0, end=1024):
    n_channels = len(channels)
    fig, axes = plt.subplots(n_channels, 1, figsize=(16, 3*n_channels), sharex=True)

    if n_channels == 1:
        axes = [axes]

    for i, ch in enumerate(channels):
        t = df_raw['lsl_timestamp'].values[start:end]
        raw_sig = df_raw[ch].values[start:end]
        filt_sig = df_filtered[ch].values[start:end]

        ax = axes[i]

        # Raw vs filtered
        ax.plot(t, raw_sig, label='Raw/Noisy', color='red', alpha=0.6)
        ax.plot(t, filt_sig, label='Filtered', color='blue')

        # --- Overlay artifact markers on filtered signal ---
        for idx, color, label in zip([flat_dict[ch], spike_dict[ch], hf_dict[ch], hv_dict[ch]],
                                     ['red','green','orange','purple'],
                                     ['Flat line','Spikes','High-Freq','High-Variance']):
            idx = np.array(idx)
            idx = idx[(idx >= start) & (idx < end)]
            if len(idx) > 0:
                ax.scatter(t[idx-start], filt_sig[idx-start], color=color, s=10, label=label)

        ax.set_ylabel(f'{ch} (μV)')
        ax.grid(True)
        ax.legend(loc='upper right')

    axes[-1].set_xlabel('Time (s)')
    plt.suptitle('Raw vs Filtered EEG with Artifact Markers', fontsize=16)
    plt.tight_layout(rect=[0,0,1,0.95])
    plt.show()



