import numpy as np

def normalize_signals(matrix):
    """
    Scale each signal in matrix to [-1, 1].
    """
    matrix_norm = -1 + 2 * (matrix - np.min(matrix)) / (np.max(matrix) - np.min(matrix))
    return matrix_norm

