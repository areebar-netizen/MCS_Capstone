def detect_spikes_flatlines(signal, spike_thresh=100, flatline_thresh=1e-6, window_size_sec=0.5, fs=256):
    """
    Detects spikes and flatlines in an EEG channel.

    Parameters:
        signal (np.array): 1D EEG signal
        spike_thresh (float): amplitude jump threshold for spikes (µV)
        flatline_thresh (float): minimum std threshold for flatlines (µV)
        window_size_sec (float): size of sliding window in seconds
        fs (int): sampling rate in Hz

    Returns:
        bad_indices (np.array): indices of signal marked as bad
        spike_indices (np.array): indices of spikes
        flatline_indices (np.array): indices of flatlines
    """
    N = len(signal)
    window_size = int(fs * window_size_sec)
    bad_indices = []
    spike_indices = []
    flatline_indices = []

    for start in range(0, N - window_size, window_size):
        window = signal[start:start + window_size]
        # Spike detection: large jumps
        diff_window = np.abs(np.diff(window))
        spikes = np.where(diff_window > spike_thresh)[0] + start
        spike_indices.extend(spikes)

        # Flatline detection: low std
        if np.std(window) < flatline_thresh:
            flatline_indices.extend(range(start, start + window_size))

    # Combine all bad indices
    bad_indices = np.unique(np.concatenate([spike_indices, flatline_indices]))

    return np.array(bad_indices), np.array(spike_indices), np.array(flatline_indices)

